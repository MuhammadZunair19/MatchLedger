import { test, expect } from '../../frontend/node_modules/@playwright/test';

test('registration, procurement CRUD, invoice variance and session logout', async ({ page }) => {
  const suffix = Date.now().toString();
  await page.goto('/');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.getByLabel('Full name').fill('Procurement Tester');
  await page.getByLabel('Organization name').fill(`QA Organization ${suffix}`);
  await page.getByLabel('Email address').fill(`qa-${suffix}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('test-only-password-123');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Procurement overview' })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Suppliers', exact: true }).click();
  await page.getByRole('button', { name: 'New supplier', exact: true }).click();
  await page.getByLabel('Supplier name').fill('QA Cable Supplier');
  await page.getByRole('button', { name: 'Save supplier', exact: true }).click();
  await expect(page.getByRole('table')).toContainText('QA Cable Supplier');
  await page.getByRole('navigation').getByRole('button', { name: 'Purchase orders', exact: true }).click();
  await page.getByRole('button', { name: 'New purchase order', exact: true }).click();
  await page.getByLabel('Reference number').fill('PO-QA-001');
  await page.getByRole('combobox', { name: 'Supplier', exact: true }).selectOption({ label: 'QA Cable Supplier' });
  await page.getByLabel('Description 1', { exact: true }).fill('Cable rolls');
  await page.getByLabel('Quantity 1', { exact: true }).fill('100');
  await page.getByLabel('Unit price 1', { exact: true }).fill('50');
  await page.getByRole('button', { name: 'Save purchase order', exact: true }).click();
  await expect(page.getByRole('table')).toContainText('SAR 5,000.00');
  await page.getByRole('navigation').getByRole('button', { name: 'Goods receipts', exact: true }).click();
  await page.getByRole('button', { name: 'New receipt', exact: true }).click();
  await page.getByLabel('Reference number').fill('GR-QA-001');
  await page.getByRole('combobox', { name: 'Purchase order', exact: true }).selectOption({ label: 'PO-QA-001' });
  await page.getByLabel('Quantity 1', { exact: true }).fill('90');
  await page.getByRole('button', { name: 'Save receipt', exact: true }).click();
  await expect(page.getByRole('table')).toContainText('GR-QA-001');
  await page.getByRole('navigation').getByRole('button', { name: 'Supplier invoices', exact: true }).click();
  await page.getByRole('button', { name: 'New invoice', exact: true }).click();
  await page.getByLabel('Invoice number').fill('INV-QA-001');
  await page.getByLabel('Due date').fill('2026-10-31');
  await page.getByRole('combobox', { name: 'Purchase order', exact: true }).selectOption({ label: 'PO-QA-001' });
  await page.getByLabel('Unit price 1', { exact: true }).fill('55');
  await page.getByRole('button', { name: 'Save invoice', exact: true }).click();
  await expect(page.getByRole('table')).toContainText('SAR 5,500.00');
  await page.getByRole('button', { name: 'Edit INV-QA-001', exact: true }).click();
  await page.getByLabel('Notes').fill('Reviewed by QA');
  await page.getByRole('button', { name: 'Save invoice', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Record saved');
  await page.getByRole('navigation').getByRole('button', { name: 'Matching', exact: true }).click();
  await page.getByRole('button', { name: 'New match', exact: true }).click();
  await page.getByLabel('Supplier invoice').selectOption({ label: 'INV-QA-001' });
  await page.getByLabel('Purchase order').selectOption({ label: 'PO-QA-001' });
  await page.getByText('GR-QA-001', { exact: true }).click();
  await page.getByRole('button', { name: 'Run deterministic match', exact: true }).click();
  await expect(page.getByText('INV-QA-001 against PO-QA-001')).toBeVisible();
  await expect(page.getByText(/Due date 2026-10-31/)).toBeVisible();
  await expect(page.getByText(/PRICE MISMATCH/)).toBeVisible();
  await expect(page.getByText(/QUANTITY MISMATCH/)).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Line comparison' })).toBeVisible();
  await page.getByRole('button', { name: 'New match', exact: true }).click();
  await page.getByLabel('Supplier invoice').selectOption({ label: 'INV-QA-001' });
  await page.getByLabel('Matching mode').selectOption('TWO_WAY');
  await page.getByLabel('Purchase order').selectOption({ label: 'PO-QA-001' });
  await page.getByRole('button', { name: 'Run deterministic match', exact: true }).click();
  await expect(page.getByText(/PRICE MISMATCH/)).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Exceptions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Exception register' })).toBeVisible();
  await page.getByLabel('Filter severity').selectOption('BLOCKING');
  await page.getByRole('button').filter({ hasText: 'PRICE MISMATCH' }).first().click();
  await expect(page.getByText('purchase order specifies', { exact: false })).toBeVisible();
  await page.getByLabel('Assigned reviewer').selectOption({ label: 'Procurement Tester · owner' });
  await page.getByLabel('Decision reason').fill('Authorized reviewer validated the source records for QA.');
  await page.getByRole('button', { name: 'Resolve', exact: true }).click();
  await expect(page.getByText('RESOLVED', { exact: true }).last()).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Approvals', exact: true }).click();
  await page.getByRole('button').filter({ hasText: 'INV-QA-001' }).click();
  await page.getByRole('button', { name: 'Submit for review', exact: true }).click();
  await page.getByRole('button', { name: 'Send for finance approval', exact: true }).click();
  await page.getByLabel('Decision reason').fill('QA approval after documented exception resolution.');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Approve', exact: true }).click();
  await expect(page.getByText('APPROVED', { exact: true }).first()).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Reports', exact: true }).click();
  await expect(page.getByText('Invoices processed', { exact: true })).toBeVisible();
  await expect(page.getByText('Exception register', { exact: true })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Audit trail', exact: true }).click();
  await expect(page.getByRole('table')).toContainText('invoice approved');
  await page.getByRole('navigation').getByRole('button', { name: 'Overview', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Procurement overview' })).toBeVisible();
  await expect(page.getByText('SAR 5,500.00', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard.png', fullPage: true });
  await page.getByRole('navigation').getByRole('button', { name: 'Supplier invoices', exact: true }).click();
  await page.getByRole('button', { name: 'Delete INV-QA-001', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByRole('table')).not.toContainText('INV-QA-001');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible();
  await page.getByLabel('Email address').fill(`qa-${suffix}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('test-only-password-123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Procurement overview' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'Suppliers', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Suppliers', exact: true })).toBeVisible();
  await expect(page.getByRole('table')).toContainText('QA Cable Supplier');
  await page.screenshot({ path: 'test-results/mobile-suppliers.png', fullPage: true });
});
